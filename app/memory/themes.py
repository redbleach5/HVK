"""Тихие темы архива по тексту поста — без выдуманной биографии."""

from __future__ import annotations

_PROMO_MARKERS = (
    "кэшбэк",
    "кэшбек",
    "cashback",
    "pstpnr.ru",
    "количество ограничено",
    "цена на вб",
    "цена на wb",
    "цена для вас",
    "за подробными условиями",
    "розыгрыш",
    "сертификат на",
)


def is_promotional(text: str) -> bool:
    """Рекламная вставка на стене — не голос автора."""
    low = (text or "").lower()
    return any(marker in low for marker in _PROMO_MARKERS)


_RULES: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("чай", ("чай", "чашк", "завар", "кружк", "кипят")),
    ("еда", ("завтрак", "ужин", "обед", "рецепт", "рис", "каш", "суп", "хлеб", "яйц")),
    ("дом", ("дом", "квартир", "стол", "лён", "салфет", "полк", "уют", "комнат", "окн")),
    ("свет", ("свет", "рассвет", "закат", "ламп", "утро", "тишин")),
    ("находки", ("рынок", "блошин", "винтаж", "нашла", "нашёл", "секонд")),
    ("прогулка", ("прогулк", "воздух", "лес", "улиц", "двор", "неб")),
    ("семья", ("малыш", "ребён", "доч", "сын", "декрет", "коляск")),
    ("кадр", ("фото", "кадр", "сним", "камер", "цвет")),
)


def infer_theme(text: str) -> str:
    """Одна короткая тема. Если ничего не узнали — «жизнь»."""
    low = (text or "").lower()
    if not low.strip():
        return "без текста"
    scores: list[tuple[int, str]] = []
    for theme, keys in _RULES:
        hit = sum(1 for k in keys if k in low)
        if hit:
            scores.append((hit, theme))
    if not scores:
        return "жизнь"
    scores.sort(key=lambda x: (-x[0], x[1]))
    return scores[0][1]
